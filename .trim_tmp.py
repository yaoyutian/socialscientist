import io, re, sys

BASE = 'd:/8yaodn-tmp/creative/foucault/'

def norm(t):
    return t.replace('“', '"').replace('”', '"')

def replace_paras(fname, pairs):
    path = BASE + fname
    s = io.open(path, encoding='utf-8').read()
    for prefix, new in pairs:
        prefix = norm(prefix)
        new = norm(new)
        # locate paragraph containing prefix
        idx = s.find(prefix)
        if idx < 0:
            print('MISS', fname, prefix[:30])
            continue
        start = s.rfind('\n\n', 0, idx) + 2
        end = s.find('\n\n', idx)
        if end < 0:
            end = len(s)
        s = s[:start] + new + s[end:]
    io.open(path, 'w', encoding='utf-8', newline='').write(s)
    print('done', fname, 'fffd=', s.count('\ufffd'))


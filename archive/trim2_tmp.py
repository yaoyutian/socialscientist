MARK = '## 与现有思想家的交叉对照'

def norm(t):
    return t.replace('\u201c', '"').replace('\u201d', '"')

def replace_section(fname, body):
    path = BASE + fname
    s = io.open(path, encoding='utf-8').read()
    a = s.find(MARK)
    assert a >= 0, fname
    b = s.find('\n## ', a + 5)
    assert b > a, fname
    new = norm(body).strip() + '\n\n---\n\n'
    s = s[:a] + new + s[b+1:]
    io.open(path, 'w', encoding='utf-8', newline='').write(s)
    seg = s[a:s.find('\n## ', a+5)]
    cjk = len(re.findall(r'[\u4e00-\u9fff]', seg))
    print(fname, 'cjk=', cjk, 'fffd=', s.count('\ufffd'), 'subs=', len(re.findall(r'^### ', seg, re.M)))


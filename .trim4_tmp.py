import io, re

BASE = 'd:/8yaodn-tmp/creative/foucault/'

def norm(t):
    return t.replace('\u201c', '"').replace('\u201d', '"')

def replace_paras(fname, pairs):
    path = BASE + fname
    s = io.open(path, encoding='utf-8').read()
    for prefix, new in pairs:
        prefix = norm(prefix); new = norm(new)
        idx = s.find(prefix)
        if idx < 0:
            print('MISS', fname, prefix[:26]); continue
        start = s.rfind('\n\n', 0, idx) + 2
        end = s.find('\n\n', idx)
        if end < 0: end = len(s)
        s = s[:start] + new + s[end:]
    io.open(path, 'w', encoding='utf-8', newline='').write(s)
    a = s.find('## \u4e0e\u73b0\u6709\u601d\u60f3\u5bb6\u7684\u4ea4\u53c9\u5bf9\u7167')
    b = s.find('\n## ', a+5)
    seg = s[a:b]
    print(fname, 'cjk=', len(re.findall(r'[\u4e00-\u9fff]', seg)), 'fffd=', s.count('\ufffd'))

